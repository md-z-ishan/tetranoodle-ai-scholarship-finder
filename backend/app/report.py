"""Pure function to generate consultant-grade Markdown reports from RunResult.

Includes:
- Executive Summary
- Top Ranked Recommendations with breakdown scores, evidence, apply steps, and still needed items
- Full Candidates Table with source tiers and verification statuses
- What We Could Not Verify (rejection reasons & unverified items)
- Needs from Student
- Application Statement of Purpose (SOP) with Critic audit notes
- Run Health (Telemetry summary: retries, fallbacks, fetched_via counts, LLM calls)
"""

from typing import Optional
from app.schemas import RunResult


def generate_markdown_report(result: RunResult) -> str:
    """Format a consultant-grade Markdown report from a completed RunResult."""
    profile = result.profile
    recs = result.recommendations
    health = result.run_health or {}
    counters = health.get("counters", {})

    lines = []
    lines.append(f"# Scholarship Advisory Report: {result.run_id}")
    lines.append("")
    lines.append("> **CONFIDENTIAL CONSULTANT MEMORANDUM**  ")
    lines.append("> *Generated by TetraNoodle AI Multi-Agent Scholarship Swarm*  ")
    lines.append("")
    lines.append("---")
    lines.append("")

    # Student Profile Snapshot
    lines.append("## 1. Candidate Academic Profile")
    if profile:
        lines.append(f"- **Student Name**: {profile.name or 'Applicant'}")
        lines.append(f"- **Current Degree**: {profile.degree or 'N/A'}")
        lines.append(f"- **Target Degree Level**: {profile.target_degree_level or 'Master'}")
        lines.append(f"- **Field of Study**: {profile.field or 'N/A'}")
        lines.append(f"- **Nationality**: {profile.nationality or 'Not specified'}")
        lines.append(f"- **CGPA**: {profile.cgpa or 'N/A'} / {profile.cgpa_scale or 10.0}")
        lines.append(f"- **Target Countries**: {', '.join(profile.target_countries) if profile.target_countries else 'Global'}")
        lines.append(f"- **Budget Constraints**: {profile.budget_note or 'Modest background, seeking full/substantial merit funding'}")
        if profile.skills:
            lines.append(f"- **Key Technical Competencies**: {', '.join(profile.skills[:10])}")
        if profile.projects:
            lines.append("- **Verified Projects**:")
            for p in profile.projects:
                tech = f" (Tech: {', '.join(p.tech)})" if p.tech else ""
                lines.append(f"  * **{p.name}**{tech}: {p.description or ''}")
    else:
        lines.append("*Profile information not available.*")
    lines.append("")

    # Executive Summary
    lines.append("## 2. Executive Summary")
    lines.append(result.executive_summary or "Evaluation completed across live search and university portals.")
    lines.append("")

    # Top Ranked Recommendations
    lines.append(f"## 3. Top Ranked Recommendations ({len(recs)} Viable Opportunities)")
    if recs:
        for rec in recs:
            opp = rec.opportunity
            lines.append(f"### Rank #{rec.rank}: {opp.name or 'Opportunity'} ({rec.score:.1f}/100)")
            lines.append(f"- **Awarding Institution**: {opp.organization or 'University'}")
            lines.append(f"- **Host Country**: {opp.country or 'International'}")
            lines.append(f"- **Official URL**: [{opp.url}]({opp.url}) (Source Tier: `{opp.source_tier}`)")
            lines.append(f"- **Verification Status**: `{opp.status.upper()}` (Confidence: {opp.confidence:.2f})")
            lines.append(f"- **Funding Classification**: `{opp.funding_type}`")
            dl_status_str = f" ({opp.days_left} days remaining)" if opp.days_left is not None else ""
            lines.append(f"- **Application Deadline**: {opp.deadline_text or 'Unspecified'} — Status: `{opp.deadline_status}`{dl_status_str}")
            
            if rec.score_breakdown:
                bd = rec.score_breakdown
                lines.append(f"- **Score Breakdown (0–100)**: "
                             f"Fit: {bd.fit:.1f}/40 | Funding: {bd.funding:.1f}/25 | "
                             f"Urgency: {bd.urgency:.1f}/15 | Risk: {bd.risk:.1f}/20")
            
            if rec.why_it_fits:
                lines.append(f"- **Why It Fits**: {rec.why_it_fits}")
            
            if opp.evidence:
                lines.append("- **Verified Evidence Snippets (from live official page)**:")
                for ev in opp.evidence[:3]:
                    lines.append(f"  > *\"{ev.snippet}\"*")

            if rec.how_to_apply:
                lines.append("- **Application Steps**:")
                for step in rec.how_to_apply[:4]:
                    lines.append(f"  1. {step}")

            if rec.still_needed:
                lines.append("- **Still Needed From Student**:")
                for item in rec.still_needed:
                    lines.append(f"  * {item}")
            lines.append("")
    else:
        lines.append("*No candidates met the strict viability criteria (verified/partial with open deadlines and zero blocking gaps).*")
        lines.append("")

    # Full Discovered Candidates Table
    lines.append("## 4. Full Discovery & Verification Audit Log")
    lines.append("| # | Opportunity Name | Source Tier | Verification Status | Confidence | Deadline Status |")
    lines.append("|---|---|---|---|---|---|")
    for i, v in enumerate(result.verified, 1):
        name = (v.name or v.url or "Unknown")[:45]
        lines.append(f"| {i} | {name} | `{v.source_tier}` | `{v.status}` | {v.confidence:.2f} | `{v.deadline_status}` |")
    lines.append("")

    # What We Could Not Verify
    if result.what_we_could_not_verify:
        lines.append("## 5. What We Could Not Verify (Rejections & Data Gaps)")
        for item in result.what_we_could_not_verify:
            lines.append(f"- {item}")
        lines.append("")

    # Needs From Student
    if result.needs_from_student:
        lines.append("## 6. Action Items For Student")
        for item in result.needs_from_student:
            lines.append(f"- [ ] {item}")
        lines.append("")

    # Application Statement of Purpose Draft
    lines.append("## 7. Tailored Statement of Purpose (SOP)")
    if result.draft and result.draft.text:
        lines.append(f"> **Target Opportunity**: {result.draft.opportunity_name or 'Top Recommendation'}  ")
        lines.append(f"> **Revision Count**: {result.draft.revision_count}  ")
        lines.append(f"> **Audit Status**: {result.draft.label}  ")
        lines.append("")
        lines.append("```text")
        lines.append(result.draft.text)
        lines.append("```")
        lines.append("")
        if result.draft.critic_notes:
            lines.append("### Critic Audit Notes:")
            for note in result.draft.critic_notes:
                lines.append(f"- {note}")
            lines.append("")
    else:
        lines.append("*SOP draft was not synthesized.*")
        lines.append("")

    # Swarm Health & Telemetry
    lines.append("## 8. Run Telemetry & Execution Health")
    lines.append(f"- **Total LLM Calls**: {counters.get('llm_calls', 0)}")
    lines.append(f"- **LLM Cache Hits**: {counters.get('llm_cache_hits', 0)}")
    lines.append(f"- **Search Queries Executed**: {counters.get('search_queries', 0)}")
    lines.append(f"- **Pages Crawled**: {counters.get('pages_fetched', 0)}")
    lines.append(f"- **Retries Recorded**: {health.get('retries_count', 0)}")
    lines.append(f"- **Fallbacks Executed**: {health.get('fallbacks_count', 0)}")
    lines.append(f"- **Failures Recorded**: {health.get('failures_count', 0)}")
    if result.timings:
        lines.append("- **Component Durations (seconds)**:")
        for comp, dur in result.timings.items():
            lines.append(f"  * `{comp}`: {dur:.1f}s")
    lines.append("")

    return "\n".join(lines)
